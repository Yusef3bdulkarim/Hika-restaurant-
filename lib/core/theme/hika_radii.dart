/// Corner radii: each size belongs to a kind of element (source: design `M1-Type`).
abstract final class HikaRadii {
  /// Badges.
  static const sm = 8.0;

  /// Inputs, chips, cards, snackbar.
  static const md = 12.0;

  /// Banners, loyalty card, bottom sheets, dialogs.
  static const lg = 20.0;

  /// Buttons, category images, stamp, tab indicator, search.
  static const full = 999.0;
}
